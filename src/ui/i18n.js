/** Přeloží katalogový název; cs vrací fallback. */
export function tn(lang, kind, key, fallback) {
  if (lang === 'cs') return fallback;
  const row = NAMES[kind]?.[key];
  if (!row) return fallback;
  return lang === 'de' ? row[1] : row[0];
}

export function patternName(lang, pattern, fallback) {
  if (lang === 'cs') return fallback;
  const parts = pattern.split('-');
  const oc = lang === 'de' ? ' Uhr' : " o'clock";
  const and = lang === 'de' ? ' und ' : ' and ';
  return parts.length === 2 ? `${parts[0]}${and}${parts[1]}${oc}` : `${parts[0]}${oc}`;
}

export function comfortLabel(lang, inp, fallback) {
  if (lang === 'cs') return fallback;
  const de = lang === 'de';
  if (inp.coldWork) return de ? 'Kalter Arbeitsplatz (v ≤ 0,20 m/s)' : 'Cold workplace (v ≤ 0.20 m/s)';
  if (inp.mode === 'heating') return de ? `Heizung Kat. ${inp.cat}: v ≤ ${String(inp.heatVLimit).replace('.', ',')} m/s` : `Heating cat. ${inp.cat}: v ≤ ${inp.heatVLimit} m/s`;
  return de ? `ISO 7730 Kat. ${inp.cat} (DR < ${inp.drLimit} %)` : `ISO 7730 cat. ${inp.cat} (DR < ${inp.drLimit} %)`;
}
